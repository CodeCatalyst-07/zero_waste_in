/**
 * Geometric shape badge component rendering distinctive non-color visual cues for each waste stream:
 * - wet: Circle badge
 * - dry: Square badge
 * - sanitary: Rounded-hexagon badge
 * - special_care: Triangle badge
 */
export function ShapeBadge({
  stream,
  className,
}: {
  readonly stream: Stream;
  readonly className?: string;
}): React.JSX.Element {
  switch (stream) {
    case 'wet':
      return (
        <span
          role="img"
          className={`shape-badge shape-badge--wet ${className ?? ''}`}
          aria-label="Circle badge"
        >
          <LeafIcon size={24} />
        </span>
      );
    case 'dry':
      return (
        <span
          role="img"
          className={`shape-badge shape-badge--dry ${className ?? ''}`}
          aria-label="Square badge"
        >
          <RecycleBoxIcon size={24} />
        </span>
      );
    case 'sanitary':
      return (
        <span
          role="img"
          className={`shape-badge shape-badge--sanitary ${className ?? ''}`}
          aria-label="Rounded-hexagon badge"
        >
          <WrappedPadIcon size={24} />
        </span>
      );
    case 'special_care':
      return (
        <span
          role="img"
          className={`shape-badge shape-badge--special-care ${className ?? ''}`}
          aria-label="Triangle badge"
        >
          <HazardTriangleIcon size={24} />
        </span>
      );
  }
}
